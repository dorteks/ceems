"use client";

import type { FormEvent } from "react";
import { useState } from "react";
import { useRouter } from "next/navigation";
import { KeyRound, UserRound } from "lucide-react";

import { Alert, AlertDescription } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { useAuth } from "@/lib/auth/auth";
import { toast } from "sonner";

export default function ChangePasswordPage() {
  const { user, changePassword } = useAuth();
  const router = useRouter();

  const [currentPassword, setCurrentPassword] = useState("");
  const [nextPassword, setNextPassword] = useState("");
  const [confirmPassword, setConfirmPassword] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);

  async function handleSubmit(e: FormEvent) {
    e.preventDefault();
    setError(null);

    if (nextPassword.length < 8) {
      setError("New password must be at least 8 characters.");
      return;
    }

    if (nextPassword !== confirmPassword) {
      setError("New password and confirmation do not match.");
      return;
    }

    setSaving(true);

    try {
      const result = await changePassword(currentPassword, nextPassword);

      if (!result.ok) {
        setError(result.error ?? "Unable to change password.");
        return;
      }

      setCurrentPassword("");
      setNextPassword("");
      setConfirmPassword("");

      toast.success("Password updated");

      router.push("/dashboard");
      router.refresh();
    } finally {
      setSaving(false);
    }
  }

  if (!user) {
    return null;
  }

  return (
    <div className="w-full h-full space-y-6">
      {/* Page heading */}
      <div>
        <h1 className="text-2xl font-semibold tracking-tight">My account</h1>
        <p className="text-sm text-muted-foreground">
          View your account details and manage your password.
        </p>
      </div>

      <div className="grid gap-6 lg:grid-cols-2">
        {/* User details */}
        <Card>
          <CardHeader>
            <CardTitle className="flex items-center gap-2">
              <UserRound className="size-4 text-primary" />
              Profile
            </CardTitle>
            <CardDescription>Your CEEMS account information</CardDescription>
          </CardHeader>

          <CardContent className="space-y-4 text-sm">
            <DetailRow label="Name" value={user.name ?? "Not provided"} />

            <DetailRow label="Email" value={user.email ?? "Not provided"} />

            <DetailRow
              label="Role"
              value={<Badge variant="secondary">{user.role ?? "User"}</Badge>}
            />

            <DetailRow
              label="Hub scope"
              value={
                <Badge variant="outline">
                  {user.hub === "All"
                    ? "All hubs"
                    : `${user.hub ?? "Not assigned"} hub only`}
                </Badge>
              }
            />

            <DetailRow
              label="Account status"
              value={<Badge variant="secondary">Active</Badge>}
            />
          </CardContent>
        </Card>

        {/* Change password */}
        <Card>
          <CardHeader>
            <CardTitle className="flex items-center gap-2">
              <KeyRound className="size-4 text-primary" />
              Change password
            </CardTitle>

            <CardDescription>
              {user.mustChangePassword
                ? "Your account is using a temporary password generated by an administrator."
                : "Update your account password at any time."}
            </CardDescription>
          </CardHeader>

          <CardContent>
            <form className="space-y-4" onSubmit={handleSubmit}>
              {error && (
                <Alert variant="destructive">
                  <AlertDescription>{error}</AlertDescription>
                </Alert>
              )}

              <div className="space-y-2">
                <Label htmlFor="current-password">Current password</Label>

                <Input
                  id="current-password"
                  type="password"
                  autoComplete="current-password"
                  value={currentPassword}
                  onChange={(e) => setCurrentPassword(e.target.value)}
                  required
                />
              </div>

              <div className="space-y-2">
                <Label htmlFor="next-password">New password</Label>

                <Input
                  id="next-password"
                  type="password"
                  autoComplete="new-password"
                  value={nextPassword}
                  onChange={(e) => setNextPassword(e.target.value)}
                  required
                  minLength={8}
                />

                <p className="text-xs text-muted-foreground">
                  Password must be at least 8 characters.
                </p>
              </div>

              <div className="space-y-2">
                <Label htmlFor="confirm-password">Confirm new password</Label>

                <Input
                  id="confirm-password"
                  type="password"
                  autoComplete="new-password"
                  value={confirmPassword}
                  onChange={(e) => setConfirmPassword(e.target.value)}
                  required
                  minLength={8}
                />
              </div>

              <Button type="submit" className="w-full" disabled={saving}>
                {saving ? "Saving..." : "Update password"}
              </Button>
            </form>
          </CardContent>
        </Card>
      </div>
    </div>
  );
}

function DetailRow({
  label,
  value,
}: {
  label: string;
  value: React.ReactNode;
}) {
  return (
    <div className="flex items-center justify-between gap-4 border-b border-border pb-3 last:border-0 last:pb-0">
      <span className="text-muted-foreground">{label}</span>
      <span className="text-right font-medium">{value}</span>
    </div>
  );
}
